"""Regenerate the generated code guide as part of the docs validation step."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path


def test_docs_are_current() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    generated = subprocess.check_output([sys.executable, "tools/make_docs.py"], cwd=repo_root, text=True)
    guide_path = repo_root / "docs" / "CODE_GUIDE.md"
    assert "# CODE_GUIDE" in guide_path.read_text(encoding="utf-8")
    assert "Generated by tools/make_docs.py" in guide_path.read_text(encoding="utf-8")
    assert "make_docs.py" in generated
