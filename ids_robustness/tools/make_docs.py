"""Generate the CODE_GUIDE.md file from the source docstrings."""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _module_doc(path: Path) -> str:
    """Read the module docstring from a Python file."""
    module = ast.parse(path.read_text(encoding="utf-8"))
    return ast.get_docstring(module) or "No module docstring provided."


def _function_info(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """Render a function signature and docstring."""
    args = ast.unparse(node.args)
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    signature = f"{node.name}({args}){returns}"
    return f"### `{signature}`\n\n{ast.get_docstring(node) or 'No function docstring provided.'}\n"


def build_guide() -> str:
    """Create the generated code guide."""
    lines = [
        "# CODE_GUIDE",
        "",
        "Generated by tools/make_docs.py",
        "",
        "This file is regenerated from the Python docstrings in the src/ package.",
        "",
    ]
    for file_path in sorted((ROOT / "src").glob("*.py")):
        if file_path.name == "__init__.py":
            continue
        module_doc = _module_doc(file_path)
        lines.append(f"## {file_path.name}")
        lines.append("")
        lines.append(module_doc)
        lines.append("")
        tree = ast.parse(file_path.read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                lines.append(_function_info(node))
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write the generated documentation to the docs directory."""
    docs_dir = ROOT / "docs"
    docs_dir.mkdir(exist_ok=True)
    guide_path = docs_dir / "CODE_GUIDE.md"
    guide_path.write_text(build_guide(), encoding="utf-8")
    print(f"make_docs.py wrote {guide_path}")


if __name__ == "__main__":
    main()
